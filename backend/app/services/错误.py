"""半截抽取回滚（补偿悬挂口径）共享异常。"""


class 抽取冲突(Exception):
    """同营业日在途批次未闭、或悬挂未补偿即再抽取——并发/交错失败闭。"""


class 半截抽取失败(Exception):
    """抽取中途抛错：本批已写户已全部悬挂化，失败批已落库可查。"""

    def __init__(self, 报告: dict):
        super().__init__(报告.get("失败原因", "抽取中途失败"))
        self.报告 = 报告


class 回放拒绝(Exception):
    """营业日存在在途抽取或未补偿悬挂镜，回放整票拒绝。"""


class 补偿无待办(Exception):
    """该营业日没有待补偿悬挂镜。"""
